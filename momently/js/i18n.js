// ---- i18n Engine ----
// Default to 'vi' for a Vietnamese user experience, or whatever is saved
let currentLang = localStorage.getItem('momently_lang') || 'vi';

function t(key) {
  if (!key) return '';
  return translations[currentLang]?.[key] ?? translations['en']?.[key] ?? key;
}

function setLang(lang) {
  if (lang !== 'vi' && lang !== 'en') lang = 'vi';
  currentLang = lang;
  localStorage.setItem('momently_lang', lang);
  document.documentElement.setAttribute('lang', lang);

  // 1. Text elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = t(key);
      } else {
        el.textContent = t(key);
      }
    }
  });

  // 2. Placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.placeholder = t(key);
  });

  // 3. HTML content (rich formatting)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (key) el.innerHTML = t(key);
  });

  // 4. Title attributes
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.title = t(key);
  });

  // 5. Update dual pill buttons styling in navbar if rendered
  document.querySelectorAll('.lang-pill-btn').forEach(btn => {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === currentLang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // 6. Dispatch custom event for dynamic components
  window.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

function toggleLang() {
  setLang(currentLang === 'vi' ? 'en' : 'vi');
}

function getLang() {
  return currentLang;
}
